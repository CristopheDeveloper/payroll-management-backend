CREATE TABLE NominaDetalle (
    IdNominaDetalle        INT IDENTITY(1,1) NOT NULL,
    IdNomina               INT               NOT NULL,
    IdEmpleado             INT               NOT NULL,
    IdPuesto               INT               NOT NULL,
    IdDepartamento         INT               NOT NULL,
    Salario                DECIMAL(10,2)     NOT NULL,
    TipoPago               NVARCHAR(15)      NOT NULL,
    RetencionIsr           DECIMAL(10,2)     NOT NULL,
    Isr                    DECIMAL(10,2)     NOT NULL,
    DiasPeriodo            INT               NOT NULL,
    DiasFalta              INT               NOT NULL,
    DiasSuspension         INT               NOT NULL,
    DiasPagar              INT               NOT NULL,
    HorasExtra             DECIMAL(5,2)      NOT NULL,
    SalarioDevengado       DECIMAL(10,2)     NOT NULL,
    MontoHorasExtra        DECIMAL(10,2)     NOT NULL,
    Bonificacion           DECIMAL(10,2)     NOT NULL,
    OtrosIngresosAfectos   DECIMAL(10,2)     NOT NULL,
    OtrosIngresosNoAfectos DECIMAL(10,2)     NOT NULL,
    TotalIngresos          DECIMAL(10,2)     NOT NULL,
    IgssLaboral            DECIMAL(10,2)     NOT NULL,
    OtrosDescuentos        DECIMAL(10,2)     NOT NULL,
    TotalDescuentos        DECIMAL(10,2)     NOT NULL,
    LiquidoRecibir         DECIMAL(10,2)     NOT NULL,
    IgssPatronal           DECIMAL(10,2)     NOT NULL,
    Irtra                  DECIMAL(10,2)     NOT NULL,
    Intecap                DECIMAL(10,2)     NOT NULL,
    UsuarioIng             NVARCHAR(50)      NOT NULL,
    FechaIng               DATETIME2         NOT NULL CONSTRAINT DF_NominaDetalle_FechaIng DEFAULT (SYSDATETIME()),
    UsuarioAct             NVARCHAR(50)      NULL,
    FechaAct               DATETIME2         NULL,
    CONSTRAINT PK_NominaDetalle PRIMARY KEY (IdNominaDetalle),
    CONSTRAINT UQ_NominaDetalle_Nomina_Empleado UNIQUE (IdNomina, IdEmpleado),
    CONSTRAINT FK_NominaDetalle_Nomina FOREIGN KEY (IdNomina) REFERENCES Nomina (IdNomina),
    CONSTRAINT FK_NominaDetalle_Empleado FOREIGN KEY (IdEmpleado) REFERENCES Empleado (IdEmpleado),
    CONSTRAINT FK_NominaDetalle_Puesto FOREIGN KEY (IdPuesto) REFERENCES Puesto (IdPuesto),
    CONSTRAINT FK_NominaDetalle_Departamento FOREIGN KEY (IdDepartamento) REFERENCES Departamento (IdDepartamento),
    CONSTRAINT CK_NominaDetalle_TipoPago CHECK (TipoPago IN ('EFECTIVO', 'CHEQUE', 'TRANSFERENCIA')),
    CONSTRAINT CK_NominaDetalle_DiasPeriodo CHECK (DiasPeriodo BETWEEN 1 AND 31),
    CONSTRAINT CK_NominaDetalle_Dias CHECK (DiasFalta >= 0 AND DiasSuspension >= 0 AND DiasPagar >= 0),
    CONSTRAINT CK_NominaDetalle_Horas CHECK (HorasExtra >= 0),
    CONSTRAINT CK_NominaDetalle_Isr CHECK (Isr >= 0 AND RetencionIsr >= 0 AND Isr <= RetencionIsr)
);
GO
